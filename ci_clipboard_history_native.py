def wait_for(predicate):
    deadline=time.monotonic()+8
    while not predicate():
        if time.monotonic()>deadline:raise AssertionError('Native text target timed out')
        QTest.qWait(20)


def target(root):
    app=QApplication([])
    class ImageTarget(QTextEdit):
        def keyPressEvent(self,event):
            if event.matches(QKeySequence.StandardKey.Paste):
                print(json.dumps({'target_received_paste_key':True,
                                  'clipboard_formats':app.clipboard().mimeData().formats()}),flush=True)
                if sys.platform=='darwin':
                    # Reproduce an application that handles paste later than
                    # the old 400 ms restoration timer.
                    QTimer.singleShot(650,self,self.paste)
                    return
            super().keyPressEvent(event)

        def canInsertFromMimeData(self,mime):
            return mime.hasUrls() or mime.hasImage() or super().canInsertFromMimeData(mime)

        def insertFromMimeData(self,mime):
            if mime.hasUrls():
                paths=[Path(url.toLocalFile()) for url in mime.urls()]
                output=root/'files-incoming.tmp'
                output.write_text(json.dumps([p.read_text(encoding='utf-8') for p in paths]),encoding='utf-8')
                output.replace(root/'files-incoming.json')
                return
            if not mime.hasImage():
                super().insertFromMimeData(mime)
                return
            image=mime.imageData()
            if hasattr(image,'toImage'):image=image.toImage()
            assert isinstance(image,QImage) and not image.isNull(),mime.formats()
            cursor=self.textCursor()
            cursor.insertImage(image)
            self.setTextCursor(cursor)
            assert self.document().characterAt(cursor.position()-1)=='\ufffc'
            data={'color':image.pixelColor(2,2).name(),'size':[image.width(),image.height()]}
            (root/'image-incoming.json').write_text(json.dumps(data))
            (root/'image-inserted').touch()
    editor=ImageTarget()
    editor.setWindowTitle('FlickDock isolated clipboard target')
    editor.setGeometry(85,80,380,260)
    editor.show();editor.raise_();editor.activateWindow();editor.setFocus()
    if sys.platform=='darwin':
        import AppKit
        AppKit.NSApplication.sharedApplication().activateIgnoringOtherApps_(True)
    app.clipboard().setText(SENTINEL)
    (root/'pid').write_text(str(os.getpid()))
    observations=0
    def record():
        nonlocal observations
        payload=dict(text=editor.toPlainText(),clipboard=app.clipboard().text())
        observations+=1
        pending=root/f'observed-{observations:04}.tmp'
        pending.write_text(json.dumps(payload))
        pending.replace(pending.with_suffix('.json'))
        if payload['text']!=TEXT:return
        (root/'incoming.json').write_text(json.dumps(payload))
        (root/'incoming.json').replace(root/'target.json')
    editor.textChanged.connect(record)
    QTimer.singleShot(40000,app.quit)
    return app.exec()


def current_process():
    value=front_target()
    return value[-1] if isinstance(value,tuple) else value


def native_screenshot_fixture(path):
    from AppKit import NSPasteboard, NSPasteboardItem
    from Foundation import NSData
    item=NSPasteboardItem.alloc().init()
    assert item.setData_forType_(NSData.dataWithContentsOfFile_(str(path)),'public.png')
    assert item.setData_forType_(NSData.data(),'org.nspasteboard.AutoGeneratedType')
    board=NSPasteboard.generalPasteboard()
    board.clearContents()
    assert board.writeObjects_([item])
    return 0


def cocoa_pointer(point,mode):
    import Quartz
    point=(point.x(),point.y())
    types={'move':(Quartz.kCGEventMouseMoved,), 'click':(Quartz.kCGEventLeftMouseDown,Quartz.kCGEventLeftMouseUp)}
    for kind in types[mode]:
        event=Quartz.CGEventCreateMouseEvent(None,kind,point,Quartz.kCGMouseButtonLeft)
        assert event is not None
        Quartz.CGEventPost(Quartz.kCGHIDEventTap,event)


def check_cocoa_clock():
    import statistics
    from PySide6.QtCore import QEventLoop
    from PySide6.QtWidgets import QWidget
    from display_frames import FramePulse, WindowFrames
    class PaintedWindow(QWidget):
        def paintEvent(self,event):
            self.times.append(time.perf_counter())
            painter=QPainter(self);painter.fillRect(event.rect(),QColor('#102948'));painter.end()

    measurements={}
    for mode in ('timer','display_link'):
        widget=PaintedWindow()
        widget.times=[];widget.resize(360,260);widget.show()
        QTest.qWait(120)
        clock=widget._display_frames=WindowFrames(widget)
        clock._use_cocoa_link=mode=='display_link'
        pulse=FramePulse(widget)
        frames=[];bound=[];loop=QEventLoop()
        def tick():
            frames.append(time.perf_counter())
            if pulse.clock._cocoa_link is not None:bound.append(True)
            widget.update(QRect(20,20,270,160))
        pulse.timeout.connect(tick)
        pulse.start()
        QTimer.singleShot(1700,loop.quit)
        loop.exec()
        pulse.stop()
        assert pulse.clock._cocoa_link is None, 'Idle animation kept a native callback'
        widget.hide()
        intervals=[(b-a)*1000 for a,b in zip(frames[5:],frames[6:])]
        paints=[(b-a)*1000 for a,b in zip(widget.times[5:],widget.times[6:])]
        assert intervals and paints,(mode,len(frames),len(widget.times))
        def p95(values):return round(statistics.quantiles(values,n=20,method='inclusive')[18],2)
        measurements[mode]=dict(hz=widget.screen().refreshRate(),callbacks=len(frames),paints=len(widget.times),
                                interval_p95_ms=p95(intervals),paint_interval_p95_ms=p95(paints),
                                paint_hz=round(1000/statistics.fmean(paints),2),native_link_callbacks=len(bound))
        if mode=='display_link':assert len(bound)>.9*len(frames),measurements
        else:assert not bound,measurements
        widget.close()
    return measurements


def run(root):
    from types import SimpleNamespace
    from PySide6.QtCore import QObject, Signal
    from clipboard_history_runtime import ClipboardHistory
    from platform_native import configure_menu_bar_application
    import clipboard_history_native as native
    import clipboard_history_runtime as history

    paste_traces=[]
    if sys.platform=='win32':
        original_snapshot=native._snapshot_windows_clipboard
        original_send=native._send_windows_paste
        def snapshot(user,kernel,ole,output):
            result=original_snapshot(user,kernel,ole,output)
            paste_traces.append({'clipboard_backup_completed':result,'formats':list(output)})
            return result
        def send(user,target):
            result=original_send(user,target)
            paste_traces.append({'system_paste_key_dispatched':result})
            return result
        native._snapshot_windows_clipboard=snapshot
        native._send_windows_paste=send

    original_insert=history.insert_image
    def insert(*args,**kwargs):
        try:
            result=original_insert(*args,**kwargs)
        except Exception as error:
            paste_traces.append({'paste_error':repr(error)})
            raise
        paste_traces.append({'paste_requested':result})
        return result
    history.insert_image=insert

    class ClipboardObservation(QObject):
        copy_observed=Signal(object)
        cloud_files_received=Signal(str,object,object)

        def set_local_observation(self, enabled, *, source):
            return

    class Account(QObject):
        account_changed=Signal(object)
        signed_in=False
        api=object()

    class Events(QObject):
        clipboard_changed=Signal()
        socket=None

    class PassiveShelf:
        def hide_animated(self, *, explicit):
            return

    app=QApplication([])
    configure_menu_bar_application()
    procedure=subprocess.Popen([sys.executable,__file__,'target',str(root)])
    runtime=None
    client=None
    timer=None
    front=None
    report={'ok':False,'platform':sys.platform,'delayed_native_paste_ms':650 if sys.platform=='darwin' else 0}
    try:
        wait_for(lambda:(root/'pid').is_file())
        pid=int((root/'pid').read_text())
        wait_for(lambda:current_process()==pid)
        on_mac=sys.platform=='darwin'
        if on_mac:
            from clipboard_sync import ClipboardSync
            client=ClipboardSync(Account(),Events(),root/'client',enabled=False)
        manager=SimpleNamespace(app=app,clipboard_sync=client or ClipboardObservation(),shelf=PassiveShelf())
        runtime=ClipboardHistory(manager,root/'saved')
        runtime.set_enabled(True)
        runtime.observe(('text',{'text':TEXT}))
        wait_for(lambda:len(runtime.entries)==1)
        runtime._create_panel()
        panel=runtime.panel
        if on_mac:
            from PySide6.QtWidgets import QWidget
            from platform_native import configure_passive_cocoa_panel,keep_tool_visible_when_inactive
            front=QWidget(None,Qt.Tool|Qt.FramelessWindowHint|Qt.WindowDoesNotAcceptFocus)
            front.setAttribute(Qt.WA_ShowWithoutActivating)
            keep_tool_visible_when_inactive(front)
            anchor=QRect(475,105,332,232)
            front.setGeometry(anchor)
            configure_passive_cocoa_panel(front)
            front.show()
            runtime._foreground_target=front_target()
            assert panel.place(anchor,app.primaryScreen().availableGeometry(),front=front)
            timer=QTimer(panel)
            timer.timeout.connect(lambda:panel.reconcile_pointer(QCursor.pos()))
            timer.start(12)
        else:
            panel.setGeometry(515,110,332,260)
            panel.show()
        QTest.qWait(150)
        assert current_process()==pid, 'History panel took focus from the native target'
        panel.repaint()
        activated=[]
        panel.activated.connect(activated.append)
        def row_point(key):
            panel.repaint()
            row=next(rect for part,identity,rect in panel._hits if part=='card' and identity==key)
            return (panel._paint_origin()+row.center()*panel._panel_scale).toPoint()
        key=runtime.entries[0]['id']
        point=row_point(key)
        if on_mac:
            global_point=panel.mapToGlobal(point)
            bounds=panel._panel_frame.translated(panel.mapToGlobal(QPoint()))
            assert not panel._above and abs(bounds.top()-anchor.bottom()-1-7)<1.1
            cocoa_pointer(global_point,'move')
            wait_for(lambda:panel.expanded and panel._stack_progress==1.)
            seam=QPoint(anchor.center().x(),anchor.bottom()+4)
            cocoa_pointer(seam,'move')
            QTest.qWait(220)
            assert panel.contains_companion(seam) and panel.expanded
            point=panel.mapToGlobal(row_point(key))
            cocoa_pointer(point,'move');QTest.qWait(65);cocoa_pointer(point,'click')
            report.update(painted_gap_px=round(bounds.top()-anchor.bottom()-1),cocoa_hover=True,seam_stable=True)
        else:
            QTest.mouseClick(panel,Qt.LeftButton,Qt.NoModifier,point)
        wait_for(lambda:len(activated)==1)
        def received_text():
            path=root/'target.json'
            if not path.is_file():return False
            data=json.loads(path.read_bytes())
            return data['text']==TEXT
        wait_for(received_text)
        wait_for(lambda:runtime._insert_job is None and app.clipboard().text()==SENTINEL)
        assert ClipboardHistoryStore(root/'saved').execute('list',3,0)[0]['title']==TEXT

        image=QImage(47,29,QImage.Format_ARGB32)
        image.fill(QColor(IMAGE_COLOR))
        if on_mac:
            image_path=root/'external-capture.png'
            assert image.save(str(image_path))
            subprocess.run([sys.executable,__file__,'native-screenshot-fixture',str(image_path)],check=True,timeout=15)
        else:runtime.observe(('image',{'image':image}))
        wait_for(lambda:len(runtime.entries)==2)
        if on_mac:
            app.clipboard().setText(SENTINEL)
            report['third_party_capture']=True
        panel.show_all()
        wait_for(lambda:panel._stack_progress==1.)
        panel.repaint()
        key=next(entry['id'] for entry in runtime.entries if entry['kind']=='image')
        point=row_point(key)
        assert current_process()==pid
        if on_mac:
            point=panel.mapToGlobal(point)
            cocoa_pointer(point,'move');QTest.qWait(65);cocoa_pointer(point,'click')
        else:QTest.mouseClick(panel,Qt.LeftButton,Qt.NoModifier,point)
        wait_for(lambda:len(activated)==2)
        assert activated[-1]==key,activated
        wait_for(lambda:(root/'image-inserted').is_file())
        actual=json.loads((root/'image-incoming.json').read_bytes())
        assert actual=={'color':IMAGE_COLOR,'size':[47,29]},actual
        wait_for(lambda:runtime._insert_job is None and app.clipboard().text()==SENTINEL)
        cache=root/'saved'/'clipboard-cache'/'clip-fixture'
        contents=cache/'files'
        contents.mkdir(parents=True)
        paths=[contents/'测 试.txt',contents/'Second attachment.txt']
        expected=['First attachment bytes','Second attachment bytes']
        for path,data in zip(paths,expected):path.write_text(data,encoding='utf-8')
        manager.clipboard_sync.cloud_files_received.emit('cloud-file-fixture',tuple(map(str,paths)),cache)
        wait_for(lambda:any(entry['kind']=='file' for entry in runtime.entries))
        for path in paths:path.unlink()
        panel.show_all()
        wait_for(lambda:panel._stack_progress==1.)
        panel.repaint()
        key=next(entry['id'] for entry in runtime.entries if entry['kind']=='file')
        point=row_point(key)
        assert current_process()==pid
        if on_mac:
            point=panel.mapToGlobal(point)
            cocoa_pointer(point,'move');QTest.qWait(65);cocoa_pointer(point,'click')
        else:QTest.mouseClick(panel,Qt.LeftButton,Qt.NoModifier,point)
        wait_for(lambda:(root/'files-incoming.json').is_file())
        assert json.loads((root/'files-incoming.json').read_text('utf8'))==expected
        wait_for(lambda:runtime._insert_job is None and app.clipboard().text()==SENTINEL)
        report['cloud_files_inserted']=True
        if on_mac:
            previous_images={entry['id'] for entry in runtime.entries if entry['kind']=='image'}
            screenshot=subprocess.run(['/usr/sbin/screencapture','-x','-c','-R85,80,160,100'],
                                      capture_output=True,timeout=12)
            if screenshot.returncode==0:
                wait_for(lambda:any(entry['kind']=='image' and entry['id'] not in previous_images
                                    for entry in runtime.entries))
                report['system_capture']=True
            else:
                report['system_capture']='unavailable_in_ci'
                print('macOS screencapture returned',screenshot.returncode,screenshot.stderr.decode(errors='replace'),flush=True)
            panel.hide();front.hide()
            report['frames']=check_cocoa_clock()
        report.update(ok=True,input_matches=True,image_inserted=True,original_clipboard_restored=True)
    finally:
        if not report['ok']:
            observed=sorted(root.glob('observed-*.json'))
            report.update(front_process=current_process(),history_feedback=runtime.panel._feedback if runtime and runtime.panel else None,
                          observed=json.loads(observed[-1].read_bytes()) if observed else None)
        if timer:timer.stop()
        if runtime:runtime.close()
        if client:client.close()
        if front:front.close()
        procedure.terminate()
        procedure.wait(timeout=5)
        report['paste_traces']=paste_traces
        print(json.dumps(report),flush=True)
    return 0


if __name__=='__main__':
    assert os.environ.get('GITHUB_ACTIONS')=='true' and os.environ.get('RUNNER_ENVIRONMENT')=='github-hosted'
    directory=Path(sys.argv[2]).resolve()
    assert directory.is_relative_to(Path(os.environ['RUNNER_TEMP']).resolve())
    if sys.argv[1]=='native-screenshot-fixture':raise SystemExit(native_screenshot_fixture(directory))
    directory.mkdir(parents=True,exist_ok=True)
    raise SystemExit(target(directory) if sys.argv[1]=='target' else run(directory))
