@lru_cache(maxsize=1)
def _windows_clipboard_api():
    user=_windows()
    kernel=ctypes.WinDLL('kernel32',use_last_error=True)
    ole=ctypes.WinDLL('ole32',use_last_error=True)
    gdi=ctypes.WinDLL('gdi32',use_last_error=True)
    handle=wintypes.HANDLE
    integer=wintypes.UINT
    size=ctypes.c_size_t
    for library,name,result,args in (
        (user,'CreateWindowExW',wintypes.HWND,(wintypes.DWORD,wintypes.LPCWSTR,wintypes.LPCWSTR,wintypes.DWORD,
             ctypes.c_int,ctypes.c_int,ctypes.c_int,ctypes.c_int,wintypes.HWND,handle,handle,ctypes.c_void_p)),
        (user,'DestroyWindow',wintypes.BOOL,(wintypes.HWND,)),
        (user,'OpenClipboard',wintypes.BOOL,(wintypes.HWND,)),
        (user,'CloseClipboard',wintypes.BOOL,()),
        (user,'EmptyClipboard',wintypes.BOOL,()),
        (user,'EnumClipboardFormats',integer,(integer,)),
        (user,'GetClipboardData',handle,(integer,)),
        (user,'GetClipboardFormatNameW',ctypes.c_int,(integer,wintypes.LPWSTR,ctypes.c_int)),
        (user,'SetClipboardData',handle,(integer,handle)),
        (user,'GetClipboardOwner',wintypes.HWND,()),
        (user,'GetClipboardSequenceNumber',wintypes.DWORD,()),
        (kernel,'GlobalSize',size,(handle,)),
        (kernel,'GlobalAlloc',handle,(integer,size)),
        (kernel,'GlobalLock',ctypes.c_void_p,(handle,)),
        (kernel,'GlobalUnlock',wintypes.BOOL,(handle,)),
        (kernel,'GlobalFree',handle,(handle,)),
        (ole,'OleDuplicateData',handle,(handle,ctypes.c_ushort,integer)),
        (gdi,'DeleteObject',wintypes.BOOL,(handle,)),
    ):
        fn=getattr(library,name)
        fn.restype=result
        fn.argtypes=args
    return user,kernel,ole,gdi


@contextmanager
def _open_windows_clipboard(user,owner,timeout):
    deadline=time.monotonic()+timeout
    while not user.OpenClipboard(owner):
        if time.monotonic()>=deadline:
            yield False
            return
        time.sleep(.012)
    try:
        yield True
    finally:
        user.CloseClipboard()


def _snapshot_windows_clipboard(user,kernel,ole,snapshot):
    fmt=0
    total=0
    internal=False
    name=ctypes.create_unicode_buffer(256)
    while True:
        ctypes.set_last_error(0)
        fmt=user.EnumClipboardFormats(fmt)
        if not fmt:return not ctypes.get_last_error() and (bool(snapshot) or not internal)
        if fmt>=0xC000 and user.GetClipboardFormatNameW(fmt,name,len(name)):
            if name.value in ('Ole Private Data','DataObject'):
                # These record the previous OLE owner's identity. Its actual
                # clipboard formats below are independent of that lifetime.
                internal=True
                continue
            if name.value=='FileContents':return False
        # These formats can hold owner-defined objects or private resources
        # whose handles cannot be reproduced with a byte copy.
        if fmt in (3,14,0x80,0x82,0x83,0x8E) or 0x0200<=fmt<=0x03FF:
            return False
        if len(snapshot)>=64:return False
        original=user.GetClipboardData(fmt)
        if not original:return False
        if fmt not in (2,9):  # CF_BITMAP and CF_PALETTE are separately duplicated by OLE
            length=kernel.GlobalSize(original)
            total+=length
            if not length or total>_MAX_BACKUP_BYTES:return False
        duplicate=ole.OleDuplicateData(original,fmt,2)
        if not duplicate:return False
        snapshot[fmt]=duplicate


def _windows_buffer(kernel,data):
    handle=kernel.GlobalAlloc(2,len(data))
    if not handle:return None
    pointer=kernel.GlobalLock(handle)
    if not pointer:
        kernel.GlobalFree(handle)
        return None
    try:
        ctypes.memmove(pointer,data,len(data))
    finally:
        kernel.GlobalUnlock(handle)
    return handle


def _set_windows_formats(user,formats):
    # The caller still owns a handle if SetClipboardData fails.
    success=True
    for fmt,handle in tuple(formats.items()):
        if user.SetClipboardData(fmt,handle):del formats[fmt]
        else:success=False
    return success


def _send_windows_paste(user,target):
    return _send_windows_editor_shortcut(user,target,0x56)


def _send_windows_editor_shortcut(user,target,key,*,range_start=None):
    if front_target()!=target or any(user.GetAsyncKeyState(key)&0x8000 for key in (0x10,0x11,0x12,0x5B,0x5C)):
        return False
    strokes=[(0x11,0)]
    if range_start is not None:
        strokes.extend(((range_start,0),(range_start,2),(0x10,0)))
    strokes.extend(((key,0),(key,2)))
    if range_start is not None:
        strokes.append((0x10,2))
    strokes.append((0x11,2))
    events=(_Input*len(strokes))(*(_Input(1,_InputValue(keyboard=_Keyboard(key,0,flags,0,0)))
                                  for key,flags in strokes))
    user.SendInput.argtypes=(wintypes.UINT,ctypes.POINTER(_Input),ctypes.c_int)
    return user.SendInput(len(events),events,ctypes.sizeof(_Input))==len(events)


def type_windows_editor_text(text,target,verify_editor):
    """Replace a verified selection without using the clipboard or sending Enter."""
    if (sys.platform!='win32' or not text or len(text)>24000
            or any(ord(char)<32 or ord(char) in (0x7F,0x2028,0x2029) for char in text)):
        return False
    user=_windows()
    units=[unit for (unit,) in struct.iter_unpack('<H',text.encode('utf-16-le'))]
    events=(_Input*(2*len(units)))(*(_Input(1,_InputValue(keyboard=_Keyboard(0,unit,flags,0,0)))
              for unit in units for flags in (4,6)))
    if (not verify_editor() or front_target()!=target
            or any(user.GetAsyncKeyState(key)&0x8000 for key in (0x10,0x11,0x12,0x5B,0x5C))):
        return False
    user.SendInput.argtypes=(wintypes.UINT,ctypes.POINTER(_Input),ctypes.c_int)
    return user.SendInput(len(events),events,ctypes.sizeof(_Input))==len(events)


def _paste_windows_image(png,image,target,cancel):
    from PySide6.QtCore import QBuffer,QIODevice

    bmp=QBuffer()
    if not bmp.open(QIODevice.WriteOnly) or not image.save(bmp,'BMP'):
        return False
    dib=bytes(bmp.data())[14:]  # CF_DIB omits the 14-byte BMP file header
    return _paste_windows_formats((('PNG',png),(8,dib)),target,cancel)


def _windows_file_drop(paths):
    # DROPFILES with fWide, followed by a double-NUL-terminated WCHAR list.
    return struct.pack('<IiiII',20,0,0,0,1)+('\0'.join(paths)+'\0\0').encode('utf-16-le')


def _paste_windows_formats(formats,target,cancel,*,verify_editor=None):
    user,kernel,ole,gdi=_windows_clipboard_api()
    owner=user.CreateWindowExW(0,'STATIC','',0,0,0,0,0,-3,None,None,None)  # HWND_MESSAGE
    if not owner:return False
    original,temporary={},{}
    owns_clipboard=False
    try:
        exclude=_excluded_windows_format()
        history=user.RegisterClipboardFormatW('CanIncludeInClipboardHistory')
        cloud=user.RegisterClipboardFormatW('CanUploadToCloudClipboard')
        formats=tuple((user.RegisterClipboardFormatW(fmt) if isinstance(fmt,str) else fmt,data)
                      for fmt,data in formats)
        if not all((exclude,history,cloud)) or not all(fmt for fmt,_ in formats):return False
        formats=(*formats,(exclude,bytes([1,0,0,0])),(history,bytes(4)),(cloud,bytes(4)))
        for fmt,data in formats:
            handle=_windows_buffer(kernel,data)
            if not handle:return False
            temporary[fmt]=handle
        with _open_windows_clipboard(user,owner,.16) as opened:
            if not opened or private_clipboard() or cancel.is_set() or front_target()!=target:
                return False
            if not _snapshot_windows_clipboard(user,kernel,ole,original):
                return False
            if cancel.is_set() or front_target()!=target or not user.EmptyClipboard():
                return False
            owns_clipboard=True
            try:
                installed=_set_windows_formats(user,temporary)
            finally:
                _mark_paste_change(user.GetClipboardSequenceNumber())
        # Closing or reading delayed/synthesized formats can advance the
        # sequence number even though this window still owns the image.
        temporary_sequence=user.GetClipboardSequenceNumber()
        if user.GetClipboardOwner()!=owner:return False
        _mark_paste_change(temporary_sequence)
        if (not installed or cancel.is_set() or (verify_editor is not None and not verify_editor())
                or user.GetClipboardOwner()!=owner
                or not _send_windows_paste(user,target)):return False
        # Once the key event is posted, an app can read asynchronously.
        # Even a subsequent history click cannot restore ahead of that read.
        time.sleep(_PASTE_GRACE_SECONDS)
        return True
    finally:
        try:
            if owns_clipboard and user.GetClipboardOwner()==owner:
                with _open_windows_clipboard(user,owner,1.) as opened:
                    if not opened:raise OSError('Could not reopen clipboard after history paste')
                    if user.GetClipboardOwner()==owner:
                        _mark_paste_change(user.GetClipboardSequenceNumber())
                        if not user.EmptyClipboard():raise OSError('Could not restore clipboard')
                        restored=_set_windows_formats(user,original)
                        _mark_paste_change(user.GetClipboardSequenceNumber())
                        if not restored:raise OSError('Could not restore every clipboard format')
                restored_sequence=user.GetClipboardSequenceNumber()
                if user.GetClipboardOwner()==owner:_mark_paste_change(restored_sequence)
        finally:
            for fmt,handle in (*original.items(),*temporary.items()):
                (gdi.DeleteObject if fmt in (2,9) else kernel.GlobalFree)(handle)
            user.DestroyWindow(owner)


@lru_cache(maxsize=1)
def _mac_paste_provider_type():
    import objc
    from Foundation import NSObject
    import AppKit

    class FlickDockHistoryPasteProvider(NSObject, protocols=[objc.protocolNamed('NSPasteboardItemDataProvider')]):
        def pasteboard_item_provideDataForType_(self,board,item,kind):
            try:
                # Supply every representation before acknowledging the read.
                # AppKit/Qt may request PNG and TIFF during one paste action.
                for name,data in self.formats.items():
                    if not item.setData_forType_(data,name):
                        raise OSError('Could not provide requested history representation')
            except Exception as error:
                self.error=error
            finally:
                self.received.set()

        def pasteboardFinishedWithDataProvider_(self,board):
            self.finished=True

    return FlickDockHistoryPasteProvider


def _wait_mac_paste_read(provider,board,sequence):
    from Foundation import NSDate,NSRunLoop
    deadline=time.monotonic()+3.
    loop=NSRunLoop.currentRunLoop()
    while not provider.received.is_set():
        if time.monotonic()>=deadline or board.changeCount()!=sequence:return False
        # The pasteboard owner callback can be delivered on this worker's
        # run loop. The application's GUI thread remains free throughout.
        loop.runUntilDate_(NSDate.dateWithTimeIntervalSinceNow_(.025))
        if not provider.received.is_set():provider.received.wait(.005)
    if provider.error is not None:raise provider.error
    return True


def _paste_mac_payload(payload,target,cancel,*,image=False,files=False,verify_editor=None):
    import Quartz
    import objc
    from AppKit import NSImage, NSPasteboard, NSPasteboardContentsCurrentHostOnly, NSPasteboardItem
    from Foundation import NSData, NSURL

    # Restoring the user's clipboard requires reading it first. Gate that
    # read before touching any data so repeated card clicks cannot prompt TCC.
    reason=mac_history_paste_blocker()
    if reason=='accessibility':return MacPasteResult.ACCESSIBILITY
    if reason=='clipboard':return MacPasteResult.CLIPBOARD_PERMISSION
    with objc.autorelease_pool():
        board=NSPasteboard.generalPasteboard()
        baseline=board.changeCount()
        if private_clipboard(image=True):return MacPasteResult.PRIVATE_CLIPBOARD
        original=[]
        total=0
        existing=board.pasteboardItems()
        if not existing and board.types():return MacPasteResult.BACKUP_UNAVAILABLE
        for item in existing or ():
            backup=NSPasteboardItem.alloc().init()
            for fmt in item.types():
                data=item.dataForType_(fmt)
                if data is None:return MacPasteResult.BACKUP_UNAVAILABLE
                total+=data.length()
                if total>_MAX_BACKUP_BYTES or not backup.setData_forType_(data,fmt):
                    return MacPasteResult.BACKUP_UNAVAILABLE
            original.append(backup)
        formats={}
        if files:
            values=[]
            for path in payload:
                url=NSURL.fileURLWithPath_(path)
                raw=url.absoluteString().encode('utf8')
                values.append({'public.file-url':NSData.dataWithBytes_length_(raw,len(raw))})
        elif image:
            data=NSData.dataWithBytes_length_(payload,len(payload))
            formats['public.png']=data
            native_image=NSImage.alloc().initWithData_(data)
            tiff=native_image.TIFFRepresentation() if native_image is not None else None
            if tiff is not None:formats['public.tiff']=tiff
        else:
            encoded=payload.encode('utf8')
            formats['public.utf8-plain-text']=NSData.dataWithBytes_length_(encoded,len(encoded))
        providers=[];items=[];received=Event()
        marker=uuid4().bytes
        native_marker=NSData.dataWithBytes_length_(marker,len(marker))
        for entry in values if files else (formats,):
            item=NSPasteboardItem.alloc().init()
            provider=_mac_paste_provider_type().alloc().init()
            provider.formats=entry
            provider.received=received
            provider.error=None
            provider.finished=False
            if not item.setDataProvider_forTypes_(provider,list(entry)):return MacPasteResult.UNAVAILABLE
            for privacy_type in ('org.nspasteboard.TransientType','org.nspasteboard.ConcealedType',_MAC_GENERATED):
                if not item.setData_forType_(NSData.data(),privacy_type):return MacPasteResult.UNAVAILABLE
            if not item.setData_forType_(native_marker,_MAC_HISTORY_PASTE):return MacPasteResult.UNAVAILABLE
            items.append(item);providers.append(provider)
        down=Quartz.CGEventCreateKeyboardEvent(None,9,True)  # kVK_ANSI_V
        up=Quartz.CGEventCreateKeyboardEvent(None,9,False)
        if down is None or up is None:return MacPasteResult.UNAVAILABLE
        if cancel.is_set():return MacPasteResult.CANCELLED
        if front_target()!=target:return MacPasteResult.FOCUS
        if board.changeCount()!=baseline:return MacPasteResult.CLIPBOARD_CHANGED
        sequence=board.prepareForNewContentsWithOptions_(NSPasteboardContentsCurrentHostOnly)
        _mark_paste_change(sequence)
        try:
            installed=board.writeObjects_(items)
            sequence=board.changeCount()
            _mark_paste_change(sequence)
            if not installed:return MacPasteResult.UNAVAILABLE
            if cancel.is_set():return MacPasteResult.CANCELLED
            if front_target()!=target:return MacPasteResult.FOCUS
            if verify_editor is not None and not verify_editor():return MacPasteResult.FOCUS
            if board.changeCount()!=sequence:return MacPasteResult.CLIPBOARD_CHANGED
            if front_target()!=target:return MacPasteResult.FOCUS
            for event in (down,up):
                Quartz.CGEventSetFlags(event,Quartz.kCGEventFlagMaskCommand)
                Quartz.CGEventPostToPid(target,event)
            if not _wait_mac_paste_read(providers[0],board,sequence):
                if board.changeCount()!=sequence:return MacPasteResult.CLIPBOARD_CHANGED
                return MacPasteResult.DESTINATION_DID_NOT_READ
            # Cocoa/Qt may read file URL data while checking supported types,
            # before the receiving app handles an asynchronous Paste action.
            # Give file consumers time after that first read as well.
            time.sleep(_MAC_FILE_PASTE_GRACE_SECONDS if files else _PASTE_GRACE_SECONDS)
            for provider in providers:
                if provider.error is not None:raise provider.error
            return MacPasteResult.INSERTED
        finally:
            current=board.changeCount()
            if current!=sequence:
                latest=board.pasteboardItems() or ()
                # Restore on native republishing only if the items still
                # belong to this paste. Some apps re-export bare file URLs.
                if len(latest)==len(items):
                    marked=all(bytes(item.dataForType_(_MAC_HISTORY_PASTE) or b'')==marker for item in latest)
                    # A sequence that still carries this paste's marker belongs
                    # to the temporary replacement, even when the platform
                    # advanced it without announcing a new copy.
                    if marked:_mark_paste_change(current)
                    if marked or files and _mac_pasteboard_has_files(latest,payload):sequence=current
            if board.changeCount()==sequence:
                # Restoring the old contents must not generate a new Universal Clipboard copy.
                _mark_paste_change(board.prepareForNewContentsWithOptions_(NSPasteboardContentsCurrentHostOnly))
                if original and not board.writeObjects_(original):raise OSError('Could not restore clipboard formats')
                _mark_paste_change(board.changeCount())


def _mac_pasteboard_has_files(items,paths):
    from Foundation import NSURL
    actual=[]
    for item in items:
        raw=item.stringForType_('public.file-url')
        url=NSURL.URLWithString_(raw) if raw else None
        if url is None or not url.isFileURL() or url.path() is None:return False
        identity=_mac_file_identity(str(url.path()))
        if identity is None:return False
        actual.append(identity)
    expected=[_mac_file_identity(path) for path in paths]
    return None not in expected and sorted(actual)==sorted(expected)


def _insert_mac_history(payload,target,*,cancel=None,image=False,files=False,verify_editor=None):
    if not payload:return MacPasteResult.UNAVAILABLE
    if target is None or front_target()!=target:return MacPasteResult.FOCUS
    cancel=cancel or Event()
    if cancel.is_set():return MacPasteResult.CANCELLED
    if not _IMAGE_PASTE_LOCK.acquire(blocking=False):return MacPasteResult.BUSY
    try:
        if image:
            from clipboard_history_store import decode_history_image, encode_png
            decoded=decode_history_image(payload)
            if decoded.isNull() or decoded.sizeInBytes()>_MAX_BACKUP_BYTES:return MacPasteResult.UNAVAILABLE
            if not payload.startswith(b'\x89PNG\r\n\x1a\n'):payload=encode_png(decoded)
        if files and not all(Path(path).is_absolute() and Path(path).exists() for path in payload):
            return MacPasteResult.UNAVAILABLE
        local_value=(('files',list(payload)) if files else ('image',dict(raw=payload)) if image
                     else ('text',dict(text=payload)))
        # The fence covers the whole replacement, its restore and the settle
        # window after it, so nothing can publish the temporary payload.
        with history_paste_scope(local_value):
            options={'verify_editor':verify_editor} if verify_editor is not None else {}
            return _paste_mac_payload(payload,target,cancel,image=image,files=files,**options)
    finally:
        _IMAGE_PASTE_LOCK.release()


def select_editor_text(target,*,within_editor=False):
    """Send the normal Select All command to the foreground editor."""
    if target is None or front_target()!=target:return False
    if sys.platform=='win32':
        user=_windows()
        if within_editor:
            # Ctrl+End and Ctrl+Shift+Home are confined to the active editor
            # in Chromium, even when the host handles Ctrl+A itself.
            return _send_windows_editor_shortcut(user,target,0x24,range_start=0x23)
        return _send_windows_editor_shortcut(user,target,0x41)
    if sys.platform=='darwin':
        import Quartz
        command=Quartz.kCGEventFlagMaskCommand
        # Keep the selection inside rich editors whose Select All menu action
        # is delegated to the containing page rather than to the text field.
        strokes=((125,command),(126,command|Quartz.kCGEventFlagMaskShift)) if within_editor else ((0,command),)
        for key,flags in strokes:
            events=[Quartz.CGEventCreateKeyboardEvent(None,key,pressed) for pressed in (True,False)]
            if any(event is None for event in events) or front_target()!=target:return False
            for event in events:
                Quartz.CGEventSetFlags(event,flags)
                Quartz.CGEventPostToPid(target,event)
        return True
    return False


def paste_editor_text(text,target,cancel,verify_editor):
    """Paste plain text with a protected, temporary clipboard and verified focus."""
    if sys.platform=='darwin':
        return _insert_mac_history(text,target,cancel=cancel,verify_editor=verify_editor)
    if sys.platform!='win32' or not _IMAGE_PASTE_LOCK.acquire(blocking=False):
        return False
    try:
        native_text=text.replace('\r\n','\n').replace('\r','\n').replace('\n','\r\n')
        with history_paste_scope(('text',dict(text=text))):
            return _paste_windows_formats(((13,(native_text+'\0').encode('utf-16-le')),),
                                          target,cancel,verify_editor=verify_editor)
    finally:
        _IMAGE_PASTE_LOCK.release()

def insert_image(png,target,*,cancel=None):
    """Paste an image while preserving a snapshot of the user's clipboard."""
    if sys.platform=='darwin':return _insert_mac_history(png,target,cancel=cancel,image=True)
    if not png or target is None or front_target()!=target:
        return False
    cancel=cancel or Event()
    if cancel.is_set() or not _IMAGE_PASTE_LOCK.acquire(blocking=False):return False
    try:
        from PySide6.QtGui import QImage
        from clipboard_history_store import encode_png

        image=QImage.fromData(png)
        if image.isNull() or image.sizeInBytes()>_MAX_BACKUP_BYTES or cancel.is_set():
            return False
        if not png.startswith(b'\x89PNG\r\n\x1a\n'):
            png=encode_png(image)
        if sys.platform=='win32':
            with history_paste_scope(('image',dict(raw=png))):
                return _paste_windows_image(png,image,target,cancel)
        return False
    finally:
        _IMAGE_PASTE_LOCK.release()


def insert_files(paths,target,*,cancel=None):
    """Send native Paste with file URLs, then restore the clipboard snapshot."""
    if sys.platform=='darwin':return _insert_mac_history(paths,target,cancel=cancel,files=True)
    cancel=cancel or Event()
    if not paths or target is None or front_target()!=target or cancel.is_set():return False
    if not all(Path(path).is_absolute() and Path(path).exists() for path in paths):return False
    if not _IMAGE_PASTE_LOCK.acquire(blocking=False):return False
    try:
        if sys.platform=='win32':
            with history_paste_scope(('files',list(paths))):
                return _paste_windows_formats(((15,_windows_file_drop(paths)),('Preferred DropEffect',struct.pack('<I',1))),target,cancel)
        return False
    finally:
        _IMAGE_PASTE_LOCK.release()
