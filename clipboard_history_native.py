"""Inspect clipboard privacy flags and paste history into the focused app."""
from __future__ import annotations

import ctypes
from collections import deque
from contextlib import contextmanager
from ctypes import wintypes
from functools import lru_cache
from itertools import groupby
import os
import sys
import time
from threading import Event, Lock


@lru_cache(maxsize=1)
def _windows():
    user=ctypes.WinDLL('user32',use_last_error=True)
    user.GetForegroundWindow.restype=wintypes.HWND
    user.GetWindowThreadProcessId.argtypes=(wintypes.HWND,ctypes.POINTER(wintypes.DWORD))
    user.IsClipboardFormatAvailable.argtypes=(wintypes.UINT,)
    user.RegisterClipboardFormatW.argtypes=(wintypes.LPCWSTR,)
    return user


@lru_cache(maxsize=1)
def _excluded_windows_format():
    return _windows().RegisterClipboardFormatW('ExcludeClipboardContentFromMonitorProcessing')


def private_clipboard():
    if sys.platform=='win32':
        return bool(_windows().IsClipboardFormatAvailable(_excluded_windows_format()))
    if sys.platform=='darwin':
        from AppKit import NSPasteboard
        names=NSPasteboard.generalPasteboard().types() or []
        return any(name in names for name in ('org.nspasteboard.ConcealedType',
                   'org.nspasteboard.TransientType','org.nspasteboard.AutoGeneratedType'))
    return False


def front_target():
    if sys.platform=='win32':
        user=_windows()
        window=user.GetForegroundWindow()
        if not window:return None
        process=wintypes.DWORD()
        if not user.GetWindowThreadProcessId(window,ctypes.byref(process)) or process.value==os.getpid():return None
        return window,process.value
    if sys.platform=='darwin':
        from AppKit import NSWorkspace
        front=NSWorkspace.sharedWorkspace().frontmostApplication()
        if front is None or front.processIdentifier()==os.getpid():return None
        return front.processIdentifier()
    return None


class _Keyboard(ctypes.Structure):
    _fields_=[('key',wintypes.WORD),('scan',wintypes.WORD),('flags',wintypes.DWORD),
              ('time',wintypes.DWORD),('extra',ctypes.c_size_t)]


class _Mouse(ctypes.Structure):
    _fields_=[('x',wintypes.LONG),('y',wintypes.LONG),('data',wintypes.DWORD),('flags',wintypes.DWORD),
              ('time',wintypes.DWORD),('extra',ctypes.c_size_t)]


class _InputValue(ctypes.Union):
    _fields_=[('mouse',_Mouse),('keyboard',_Keyboard)]


class _Input(ctypes.Structure):
    _fields_=[('kind',wintypes.DWORD),('value',_InputValue)]


def _send_windows_packet(user,text):
    encoded=text.encode('utf-16-le')
    units=[int.from_bytes(encoded[index:index+2],'little') for index in range(0,len(encoded),2)]
    events=(_Input*(2*len(units)))()
    for index,unit in enumerate(units):
        events[2*index]=_Input(1,_InputValue(keyboard=_Keyboard(0,unit,4,0,0)))
        events[2*index+1]=_Input(1,_InputValue(keyboard=_Keyboard(0,unit,6,0,0)))
    user.SendInput.argtypes=(wintypes.UINT,ctypes.POINTER(_Input),ctypes.c_int)
    return user.SendInput(len(events),events,ctypes.sizeof(_Input))==len(events)


def _send_windows(text,target,cancel):
    user=_windows()
    # Qt queues ordinary key events but commits surrogate pairs immediately
    # through its input method. Give the preceding native batch time to
    # dispatch on its own before switching between those two paths.
    groups=[''.join(chars) for _,chars in groupby(text,key=lambda char:ord(char)>0xFFFF)]
    if len(groups)>32:return False
    for index,chars in enumerate(groups):
        if index and cancel.wait(.045):return False
        if cancel.is_set() or front_target()!=target:return False
        if any(user.GetAsyncKeyState(key)&0x8000 for key in (0x10,0x11,0x12,0x5B,0x5C)):return False
        if not _send_windows_packet(user,chars):return False
    return True


def _send_mac(text,target,cancel):
    import Quartz
    if not Quartz.CGPreflightPostEventAccess():return False
    for start in range(0,len(text),8):
        if cancel.is_set() or front_target()!=target:return False
        piece=text[start:start+8]
        length=len(piece.encode('utf-16-le'))//2
        down=Quartz.CGEventCreateKeyboardEvent(None,0,True)
        up=Quartz.CGEventCreateKeyboardEvent(None,0,False)
        if down is None or up is None:return False
        Quartz.CGEventKeyboardSetUnicodeString(down,length,piece)
        Quartz.CGEventKeyboardSetUnicodeString(up,length,piece)
        Quartz.CGEventPostToPid(target,down)
        Quartz.CGEventPostToPid(target,up)
    return True


def insert_text(text,target,*,cancel=None):
    if not text or len(text)>4096 or target is None or front_target()!=target:return False
    if any(ord(char)<32 and char not in ('\r','\n','\t') for char in text):return False
    cancel=cancel or Event()
    if sys.platform=='win32':return _send_windows(text,target,cancel)
    if sys.platform=='darwin':return _send_mac(text,target,cancel)
    return False

# Native Clipboard observers use the OS change number. A temporary paste and
# its restoration are one local action, never a new copy event for sync.
_IMAGE_PASTE_LOCK=Lock()
_IMAGE_PASTE_SEQUENCES=deque(maxlen=12)
_MAX_BACKUP_BYTES=96*1024*1024
_PASTE_GRACE_SECONDS=.40


def image_paste_active():
    return _IMAGE_PASTE_LOCK.locked()


def image_paste_change(sequence):
    return sequence is not None and sequence in _IMAGE_PASTE_SEQUENCES.copy()


def _mark_paste_change(sequence):
    if sequence:
        _IMAGE_PASTE_SEQUENCES.append(sequence)


@lru_cache(maxsize=1)
def _windows_clipboard_api():
    user=_windows()
    kernel=ctypes.WinDLL('kernel32',use_last_error=True)
    ole=ctypes.WinDLL('ole32',use_last_error=True)
    gdi=ctypes.WinDLL('gdi32',use_last_error=True)
    handle=wintypes.HANDLE
    integer=wintypes.UINT
    size=ctypes.c_size_t
    for library,name,result,args in (
        (user,'CreateWindowExW',wintypes.HWND,(wintypes.DWORD,wintypes.LPCWSTR,wintypes.LPCWSTR,wintypes.DWORD,
             ctypes.c_int,ctypes.c_int,ctypes.c_int,ctypes.c_int,wintypes.HWND,handle,handle,ctypes.c_void_p)),
        (user,'DestroyWindow',wintypes.BOOL,(wintypes.HWND,)),
        (user,'OpenClipboard',wintypes.BOOL,(wintypes.HWND,)),
        (user,'CloseClipboard',wintypes.BOOL,()),
        (user,'EmptyClipboard',wintypes.BOOL,()),
        (user,'EnumClipboardFormats',integer,(integer,)),
        (user,'GetClipboardData',handle,(integer,)),
        (user,'GetClipboardFormatNameW',ctypes.c_int,(integer,wintypes.LPWSTR,ctypes.c_int)),
        (user,'SetClipboardData',handle,(integer,handle)),
        (user,'GetClipboardOwner',wintypes.HWND,()),
        (user,'GetClipboardSequenceNumber',wintypes.DWORD,()),
        (kernel,'GlobalSize',size,(handle,)),
        (kernel,'GlobalAlloc',handle,(integer,size)),
        (kernel,'GlobalLock',ctypes.c_void_p,(handle,)),
        (kernel,'GlobalUnlock',wintypes.BOOL,(handle,)),
        (kernel,'GlobalFree',handle,(handle,)),
        (ole,'OleDuplicateData',handle,(handle,ctypes.c_ushort,integer)),
        (gdi,'DeleteObject',wintypes.BOOL,(handle,)),
    ):
        fn=getattr(library,name)
        fn.restype=result
        fn.argtypes=args
    return user,kernel,ole,gdi


@contextmanager
def _open_windows_clipboard(user,owner,timeout):
    deadline=time.monotonic()+timeout
    while not user.OpenClipboard(owner):
        if time.monotonic()>=deadline:
            yield False
            return
        time.sleep(.012)
    try:
        yield True
    finally:
        user.CloseClipboard()


def _snapshot_windows_clipboard(user,kernel,ole,snapshot):
    fmt=0
    total=0
    internal=False
    name=ctypes.create_unicode_buffer(256)
    while True:
        ctypes.set_last_error(0)
        fmt=user.EnumClipboardFormats(fmt)
        if not fmt:return not ctypes.get_last_error() and (bool(snapshot) or not internal)
        if fmt>=0xC000 and user.GetClipboardFormatNameW(fmt,name,len(name)):
            if name.value in ('Ole Private Data','DataObject'):
                # These record the previous OLE owner's identity. Its actual
                # clipboard formats below are independent of that lifetime.
                internal=True
                continue
            if name.value=='FileContents':return False
        # These formats can hold owner-defined objects or private resources
        # whose handles cannot be reproduced with a byte copy.
        if fmt in (3,14,0x80,0x82,0x83,0x8E) or 0x0200<=fmt<=0x03FF:
            return False
        if len(snapshot)>=64:return False
        original=user.GetClipboardData(fmt)
        if not original:return False
        if fmt not in (2,9):  # CF_BITMAP and CF_PALETTE are separately duplicated by OLE
            length=kernel.GlobalSize(original)
            total+=length
            if not length or total>_MAX_BACKUP_BYTES:return False
        duplicate=ole.OleDuplicateData(original,fmt,2)
        if not duplicate:return False
        snapshot[fmt]=duplicate


def _windows_buffer(kernel,data):
    handle=kernel.GlobalAlloc(2,len(data))
    if not handle:return None
    pointer=kernel.GlobalLock(handle)
    if not pointer:
        kernel.GlobalFree(handle)
        return None
    try:
        ctypes.memmove(pointer,data,len(data))
    finally:
        kernel.GlobalUnlock(handle)
    return handle


def _set_windows_formats(user,formats):
    # The caller still owns a handle if SetClipboardData fails.
    success=True
    for fmt,handle in tuple(formats.items()):
        if user.SetClipboardData(fmt,handle):del formats[fmt]
        else:success=False
    return success


def _send_windows_paste(user,target):
    if front_target()!=target or any(user.GetAsyncKeyState(key)&0x8000 for key in (0x10,0x11,0x12,0x5B,0x5C)):
        return False
    events=(_Input*4)(*(_Input(1,_InputValue(keyboard=_Keyboard(key,0,flags,0,0)))
                       for key,flags in ((0x11,0),(0x56,0),(0x56,2),(0x11,2))))
    user.SendInput.argtypes=(wintypes.UINT,ctypes.POINTER(_Input),ctypes.c_int)
    return user.SendInput(len(events),events,ctypes.sizeof(_Input))==len(events)


def _paste_windows_image(png,image,target,cancel):
    from PySide6.QtCore import QBuffer,QIODevice

    bmp=QBuffer()
    if not bmp.open(QIODevice.WriteOnly) or not image.save(bmp,'BMP'):
        return False
    dib=bytes(bmp.data())[14:]  # CF_DIB omits the 14-byte BMP file header
    user,kernel,ole,gdi=_windows_clipboard_api()
    owner=user.CreateWindowExW(0,'STATIC','',0,0,0,0,0,-3,None,None,None)  # HWND_MESSAGE
    if not owner:return False
    original,temporary={},{}
    owns_image=False
    try:
        png_type=user.RegisterClipboardFormatW('PNG')
        exclude=_excluded_windows_format()
        history=user.RegisterClipboardFormatW('CanIncludeInClipboardHistory')
        cloud=user.RegisterClipboardFormatW('CanUploadToCloudClipboard')
        if not all((png_type,exclude,history,cloud)):return False
        formats=((png_type,png),(8,dib),(exclude,bytes([1,0,0,0])),(history,bytes(4)),(cloud,bytes(4)))
        for fmt,data in formats:
            handle=_windows_buffer(kernel,data)
            if not handle:return False
            temporary[fmt]=handle
        with _open_windows_clipboard(user,owner,.16) as opened:
            if not opened or private_clipboard() or cancel.is_set() or front_target()!=target:
                return False
            if not _snapshot_windows_clipboard(user,kernel,ole,original):
                return False
            if cancel.is_set() or front_target()!=target or not user.EmptyClipboard():
                return False
            owns_image=True
            try:
                installed=_set_windows_formats(user,temporary)
            finally:
                _mark_paste_change(user.GetClipboardSequenceNumber())
        # Closing or reading delayed/synthesized formats can advance the
        # sequence number even though this window still owns the image.
        temporary_sequence=user.GetClipboardSequenceNumber()
        if user.GetClipboardOwner()!=owner:return False
        _mark_paste_change(temporary_sequence)
        if not installed or cancel.is_set() or not _send_windows_paste(user,target):return False
        # Once the key event is posted, an app can read asynchronously.
        # Even a subsequent history click cannot restore ahead of that read.
        time.sleep(_PASTE_GRACE_SECONDS)
        return True
    finally:
        try:
            if owns_image and user.GetClipboardOwner()==owner:
                with _open_windows_clipboard(user,owner,1.) as opened:
                    if not opened:raise OSError('Could not reopen clipboard after image paste')
                    if user.GetClipboardOwner()==owner:
                        _mark_paste_change(user.GetClipboardSequenceNumber())
                        if not user.EmptyClipboard():raise OSError('Could not restore clipboard')
                        restored=_set_windows_formats(user,original)
                        _mark_paste_change(user.GetClipboardSequenceNumber())
                        if not restored:raise OSError('Could not restore every clipboard format')
                restored_sequence=user.GetClipboardSequenceNumber()
                if user.GetClipboardOwner()==owner:_mark_paste_change(restored_sequence)
        finally:
            for fmt,handle in (*original.items(),*temporary.items()):
                (gdi.DeleteObject if fmt in (2,9) else kernel.GlobalFree)(handle)
            user.DestroyWindow(owner)


def _paste_mac_image(png,target,cancel):
    import Quartz
    import objc
    from AppKit import NSPasteboard,NSPasteboardItem
    from Foundation import NSData

    if not Quartz.CGPreflightPostEventAccess():return False
    with objc.autorelease_pool():
        board=NSPasteboard.generalPasteboard()
        baseline=board.changeCount()
        if private_clipboard():return False
        original=[]
        total=0
        for item in board.pasteboardItems() or ():
            backup=NSPasteboardItem.alloc().init()
            for fmt in item.types():
                data=item.dataForType_(fmt)
                if data is None:return False
                total+=data.length()
                if total>_MAX_BACKUP_BYTES or not backup.setData_forType_(data,fmt):return False
            original.append(backup)
        item=NSPasteboardItem.alloc().init()
        data=NSData.dataWithBytes_length_(png,len(png))
        if not item.setData_forType_(data,'public.png'):return False
        if not item.setData_forType_(NSData.data(),'org.nspasteboard.TransientType'):return False
        down=Quartz.CGEventCreateKeyboardEvent(None,9,True)  # kVK_ANSI_V
        up=Quartz.CGEventCreateKeyboardEvent(None,9,False)
        if down is None or up is None or cancel.is_set() or front_target()!=target or board.changeCount()!=baseline:
            return False
        sequence=board.clearContents()
        _mark_paste_change(sequence)
        try:
            installed=board.writeObjects_([item])
            sequence=board.changeCount()
            _mark_paste_change(sequence)
            if not installed or cancel.is_set() or front_target()!=target:return False
            for event in (down,up):
                Quartz.CGEventSetFlags(event,Quartz.kCGEventFlagMaskCommand)
                Quartz.CGEventPostToPid(target,event)
            time.sleep(_PASTE_GRACE_SECONDS)
            return True
        finally:
            if board.changeCount()==sequence:
                _mark_paste_change(board.clearContents())
                if original and not board.writeObjects_(original):raise OSError('Could not restore clipboard formats')
                _mark_paste_change(board.changeCount())


def insert_image(png,target,*,cancel=None):
    """Paste an image while preserving a snapshot of the user's clipboard."""
    if not png or target is None or front_target()!=target:
        return False
    cancel=cancel or Event()
    if cancel.is_set() or not _IMAGE_PASTE_LOCK.acquire(blocking=False):return False
    try:
        from PySide6.QtGui import QImage
        from clipboard_history_store import encode_png

        image=QImage.fromData(png)
        if image.isNull() or image.sizeInBytes()>_MAX_BACKUP_BYTES or cancel.is_set():
            return False
        if not png.startswith(b'\x89PNG\r\n\x1a\n'):
            png=encode_png(image)
        if sys.platform=='win32':return _paste_windows_image(png,image,target,cancel)
        if sys.platform=='darwin':return _paste_mac_image(png,target,cancel)
        return False
    finally:
        _IMAGE_PASTE_LOCK.release()
