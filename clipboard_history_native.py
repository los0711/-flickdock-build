@lru_cache(maxsize=1)
def _windows():
    user=ctypes.WinDLL('user32',use_last_error=True)
    user.GetForegroundWindow.restype=wintypes.HWND
    user.GetWindowThreadProcessId.argtypes=(wintypes.HWND,ctypes.POINTER(wintypes.DWORD))
    user.IsClipboardFormatAvailable.argtypes=(wintypes.UINT,)
    user.RegisterClipboardFormatW.argtypes=(wintypes.LPCWSTR,)
    return user


@lru_cache(maxsize=1)
def _excluded_windows_format():
    return _windows().RegisterClipboardFormatW('ExcludeClipboardContentFromMonitorProcessing')


_MAC_HISTORY_PASTE='com.flickdock.history-paste'
_MAC_PRIVATE_TYPES={'org.nspasteboard.ConcealedType','org.nspasteboard.TransientType',_MAC_HISTORY_PASTE}
_MAC_GENERATED='org.nspasteboard.AutoGeneratedType'
_MAC_IMAGE_TYPES={'public.png':'image/png','public.tiff':'image/tiff','public.jpeg':'image/jpeg',
                  'org.webmproject.webp':'image/webp','public.heic':'image/heic',
                  'com.microsoft.bmp':'image/bmp','com.compuserve.gif':'image/gif'}
_MAX_NATIVE_IMAGE_BYTES=128*1024*1024


class MacPasteResult(Enum):
    INSERTED='已粘贴'
    FOCUS='未能回到原窗口，请先点一下目标输入框'
    ACCESSIBILITY='请在 Mac 权限设置中允许辅助功能'
    CLIPBOARD_PERMISSION='请在 Mac 权限设置中将剪贴板设为始终允许'
    PRIVATE_CLIPBOARD='当前剪贴板包含受保护内容，已保留原内容'
    BACKUP_UNAVAILABLE='当前剪贴板无法完整备份，已保留原内容'
    CLIPBOARD_CHANGED='剪贴板刚刚更新，请再点击一次'
    DESTINATION_DID_NOT_READ='目标应用未读取这次粘贴，请检查插入位置是否支持此内容'
    BUSY='上一次粘贴正在结束，请稍后再试'
    UNAVAILABLE='这条历史内容暂时无法粘贴'
    CANCELLED='粘贴已取消'

    def __bool__(self):
        return self is MacPasteResult.INSERTED


def mac_clipboard_image(board):
    # Inspect the actual raster UTIs before Qt synthesizes a MIME type.
    names=set(board.types() or ())
    if names & _MAC_PRIVATE_TYPES:return None
    for native_type,mime in _MAC_IMAGE_TYPES.items():
        if native_type not in names:continue
        data=board.dataForType_(native_type)
        if data is not None and 0<data.length()<=_MAX_NATIVE_IMAGE_BYTES:
            return 'image',dict(raw=bytes(data),mime=mime)
    return None


def private_clipboard(*,image=False):
    if sys.platform=='win32':
        return bool(_windows().IsClipboardFormatAvailable(_excluded_windows_format()))
    if sys.platform=='darwin':
        from AppKit import NSPasteboard
        names=NSPasteboard.generalPasteboard().types() or []
        return bool(_MAC_PRIVATE_TYPES.intersection(names)) or (not image and _MAC_GENERATED in names)
    return False


def front_target():
    if sys.platform=='win32':
        user=_windows()
        window=user.GetForegroundWindow()
        if not window:return None
        process=wintypes.DWORD()
        if not user.GetWindowThreadProcessId(window,ctypes.byref(process)) or process.value==os.getpid():return None
        return window,process.value
    if sys.platform=='darwin':
        from AppKit import NSWorkspace
        front=NSWorkspace.sharedWorkspace().frontmostApplication()
        if front is None or front.processIdentifier()==os.getpid():return None
        return front.processIdentifier()
    return None


def mac_owns_foreground():
    from AppKit import NSWorkspace
    front=NSWorkspace.sharedWorkspace().frontmostApplication()
    return front is not None and front.processIdentifier()==os.getpid()


def restore_mac_target(pid):
    from AppKit import NSApplication, NSApplicationActivateIgnoringOtherApps, NSRunningApplication
    current=NSRunningApplication.currentApplication()
    target=NSRunningApplication.runningApplicationWithProcessIdentifier_(pid)
    if not mac_owns_foreground() or target is None or target.isTerminated():return False
    application=NSApplication.sharedApplication()
    yield_activation=getattr(application,'yieldActivationToApplication_',None)
    activate_from=getattr(target,'activateFromApplication_options_',None)
    if yield_activation is not None and activate_from is not None:
        yield_activation(target)
        return bool(activate_from(current,0))
    return bool(target.activateWithOptions_(NSApplicationActivateIgnoringOtherApps))


def mac_paste_allowed():
    from mac_permissions import MacPermissionBackend
    return MacPermissionBackend().paste()=='allowed'


def mac_history_paste_blocker():
    from mac_permissions import MacPermissionBackend
    if not mac_paste_allowed():return 'accessibility'
    if MacPermissionBackend().clipboard() not in ('allowed','legacy'):return 'clipboard'
    return None


class _Keyboard(ctypes.Structure):
    _fields_=[('key',wintypes.WORD),('scan',wintypes.WORD),('flags',wintypes.DWORD),
              ('time',wintypes.DWORD),('extra',ctypes.c_size_t)]


class _Mouse(ctypes.Structure):
    _fields_=[('x',wintypes.LONG),('y',wintypes.LONG),('data',wintypes.DWORD),('flags',wintypes.DWORD),
              ('time',wintypes.DWORD),('extra',ctypes.c_size_t)]


class _InputValue(ctypes.Union):
    _fields_=[('mouse',_Mouse),('keyboard',_Keyboard)]


class _Input(ctypes.Structure):
    _fields_=[('kind',wintypes.DWORD),('value',_InputValue)]


def _send_windows_packet(user,text):
    encoded=text.encode('utf-16-le')
    units=[int.from_bytes(encoded[index:index+2],'little') for index in range(0,len(encoded),2)]
    events=(_Input*(2*len(units)))()
    for index,unit in enumerate(units):
        events[2*index]=_Input(1,_InputValue(keyboard=_Keyboard(0,unit,4,0,0)))
        events[2*index+1]=_Input(1,_InputValue(keyboard=_Keyboard(0,unit,6,0,0)))
    user.SendInput.argtypes=(wintypes.UINT,ctypes.POINTER(_Input),ctypes.c_int)
    return user.SendInput(len(events),events,ctypes.sizeof(_Input))==len(events)


def _send_windows(text,target,cancel):
    user=_windows()
    # Qt queues ordinary key events but commits surrogate pairs immediately
    # through its input method. Give the preceding native batch time to
    # dispatch on its own before switching between those two paths.
    groups=[''.join(chars) for _,chars in groupby(text,key=lambda char:ord(char)>0xFFFF)]
    if len(groups)>32:return False
    for index,chars in enumerate(groups):
        if index and cancel.wait(.045):return False
        if cancel.is_set() or front_target()!=target:return False
        if any(user.GetAsyncKeyState(key)&0x8000 for key in (0x10,0x11,0x12,0x5B,0x5C)):return False
        if not _send_windows_packet(user,chars):return False
    return True


def insert_text(text,target,*,cancel=None):
    if not text or any(ord(char)<32 and char not in ('\r','\n','\t') for char in text):
        return MacPasteResult.UNAVAILABLE if sys.platform=='darwin' else False
    if sys.platform=='darwin':
        return _insert_mac_history(text,target,cancel=cancel)
    if target is None or front_target()!=target:return False
    cancel=cancel or Event()
    if sys.platform=='win32':return len(text)<=4096 and _send_windows(text,target,cancel)
    return False

# Native Clipboard observers use the OS change number. A temporary paste and
# its restoration are one local action, never a new copy event for sync.
_IMAGE_PASTE_LOCK=Lock()
_IMAGE_PASTE_SEQUENCES=deque(maxlen=12)
_MAX_BACKUP_BYTES=96*1024*1024
_PASTE_GRACE_SECONDS=.40
_MAC_FILE_PASTE_GRACE_SECONDS=1.
_MAC_HISTORY_ECHO_SECONDS=30.
_MAC_HISTORY_ECHOES=deque(maxlen=32)
_MAC_HISTORY_ECHO_LOCK=Lock()
# Inserting a history card temporarily owns the system clipboard. That
# replacement is one local action: no observer may publish it as a new copy or
# forward it to another device. The fence outlives the paste itself so delayed
# restores and late native notifications stay covered, and its content stamps
# identify the pasted payload even when the platform reports an extra
# sequence that was never announced by this process.
_HISTORY_PASTE_TTL_SECONDS=30.
_HISTORY_PASTE_SETTLE_SECONDS=.5
_HISTORY_PASTE_STATE_LOCK=Lock()
_HISTORY_PASTE_DEPTH=0
_HISTORY_PASTE_SETTLE_UNTIL=0.
_HISTORY_PASTE_STAMPS=deque(maxlen=64)
_HISTORY_COPY_SHORTCUT=None
_HISTORY_COPY_SEQUENCE=None
_CLIPBOARD_IMAGE_SUFFIXES=frozenset(('.png','.jpg','.jpeg','.webp','.bmp','.tif','.tiff'))


def _mac_file_identity(path):
    try:
        stat=Path(path).stat()
        return stat.st_dev,stat.st_ino,getattr(stat,'st_birthtime_ns',None)
    except (OSError,ValueError):
        return None


def _mac_history_keys(value):
    if value[0]=='files':
        return frozenset(key for path in value[1] if (key:=_mac_file_identity(path)) is not None)
    from clipboard_identity import content_keys
    return content_keys(value)


def _remember_mac_history_payload(value):
    keys=_mac_history_keys(value)
    stamp=_history_stamp(value)
    expires=None if value[0]=='files' else time.monotonic()+_MAC_HISTORY_ECHO_SECONDS
    with _MAC_HISTORY_ECHO_LOCK:
        if keys:_MAC_HISTORY_ECHOES.append((value[0],keys,expires))
        if stamp is not None:_HISTORY_PASTE_STAMPS.append((stamp,time.monotonic()+_HISTORY_PASTE_TTL_SECONDS))


def _mac_history_recent(kind):
    now=time.monotonic()
    with _MAC_HISTORY_ECHO_LOCK:
        return tuple(keys for name,keys,expires in _MAC_HISTORY_ECHOES
                     if name==kind and (expires is None or expires>=now))


@contextmanager
def history_paste_scope(value=None):
    """Fence the temporary clipboard replacement a history card performs."""
    global _HISTORY_PASTE_DEPTH,_HISTORY_PASTE_SETTLE_UNTIL
    if value is not None:_remember_mac_history_payload(value)
    with _HISTORY_PASTE_STATE_LOCK:_HISTORY_PASTE_DEPTH+=1
    try:yield
    finally:
        with _HISTORY_PASTE_STATE_LOCK:
            _HISTORY_PASTE_DEPTH=max(0,_HISTORY_PASTE_DEPTH-1)
            _HISTORY_PASTE_SETTLE_UNTIL=time.monotonic()+_HISTORY_PASTE_SETTLE_SECONDS


def history_paste_active():
    """True while a history paste runs, or while its restore is still settling."""
    with _HISTORY_PASTE_STATE_LOCK:
        return _HISTORY_PASTE_DEPTH>0 or time.monotonic()<_HISTORY_PASTE_SETTLE_UNTIL


def _history_stamp(value):
    # Identity that survives a platform republishing the payload under a new
    # sequence, a new path spelling, or a replaced inode.
    try:
        from clipboard_identity import content_keys,signature
        stamp=signature(value) if value[0]=='files' else content_keys(value)
    except (ImportError,RuntimeError,OSError,TypeError):
        return None
    if not stamp:return None
    return hashlib.sha256(repr(stamp).encode('utf8','backslashreplace')).digest()


def history_paste_echo(value):
    """True when a clipboard value is the payload a history card just pasted."""
    if not value:return False
    now=time.monotonic()
    with _MAC_HISTORY_ECHO_LOCK:
        recorded=tuple(stamp for stamp,expires in _HISTORY_PASTE_STAMPS if expires>=now)
    if not recorded:return False
    stamp=_history_stamp(value)
    return stamp is not None and stamp in recorded


def mac_history_echo_memory():
    """Whether any history payload is still remembered for echo classification."""
    now=time.monotonic()
    with _MAC_HISTORY_ECHO_LOCK:
        return any(expires is None or expires>=now for _,_,expires in _MAC_HISTORY_ECHOES)


def note_history_copy_shortcut(sequence):
    """Mark a real Copy/Cut chord while a recent local paste can be replayed."""
    global _HISTORY_COPY_SHORTCUT,_HISTORY_COPY_SEQUENCE
    if sequence is None:return
    with _HISTORY_PASTE_STATE_LOCK:
        _HISTORY_COPY_SHORTCUT=(sequence,time.monotonic()+1.5)
        _HISTORY_COPY_SEQUENCE=None


def explicit_history_copy(sequence):
    global _HISTORY_COPY_SHORTCUT,_HISTORY_COPY_SEQUENCE
    if sequence is None:return False
    with _HISTORY_PASTE_STATE_LOCK:
        if _HISTORY_COPY_SHORTCUT is None:return False
        before,expires=_HISTORY_COPY_SHORTCUT
        if time.monotonic()>=expires:
            _HISTORY_COPY_SHORTCUT=None
            return False
        if sequence!=before and _HISTORY_COPY_SEQUENCE is None:_HISTORY_COPY_SEQUENCE=sequence
        return sequence==_HISTORY_COPY_SEQUENCE


def _mac_file_from_text(value):
    from urllib.parse import unquote,urlsplit
    text=value.strip()
    if '\n' in text or '\r' in text:return None
    if text.startswith('/') and not text.startswith('//'):return text
    if not text.lower().startswith('file:'):return None
    try:url=urlsplit(text)
    except ValueError:return None
    if url.netloc.lower() in ('','localhost') and url.path.startswith('/'):return unquote(url.path)
    return None


