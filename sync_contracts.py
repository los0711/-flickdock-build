"""The local shelf boundary consumed by cloud replication; no Qt view types."""
from typing import Protocol


class ShelfStatePort(Protocol):
    def snapshot(self) -> dict: ...
    def title(self, ref: str) -> str: ...
    def cancel_pending(self) -> None: ...
    def remove_owned(self, ref: str) -> None: ...
    def restore(self, view: dict) -> None: ...
